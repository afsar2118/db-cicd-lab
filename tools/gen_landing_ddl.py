"""Generate the landing database raw tables from the src_sf view column CSVs.

One raw table per source view: same column names (lowercase) and types as the view,
"stored as received", plus two audit columns:
  load_id       -> ctl.load_log (which extract run wrote the row)
  extracted_at  -> when the extract run started
Renames applied in raw (the extract job applies the same map): see RENAMES.

Writes db/landing/migrations/V3.. one file per view. V1 (schemas) and V2 (ctl.load_log)
are hand-written. Re-run only BEFORE a migration is first applied anywhere.

Usage (from the repo root):  python tools/gen_landing_ddl.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC_DIR = ROOT / "docs/src_sf"
SQL_DIR = ROOT / "db/landing/migrations"

# view CSV -> raw table. Order fixes the V numbers: do not reorder once applied.
VIEWS = [
    "dp_title_actuals_rpt_vw",
    "dp_pnf_rpt_vw",
    "dp_cost_center_actuals_rpt_vw",
    "dp_acct_hier_rpt_vw",
    "dp_cost_ctr_hier_rpt_vw",
    "dp_business_area_hier_rpt_vw",
    "dp_company_code_hier_rpt_vw",
]
FIRST_VERSION = 3
RENAMES = {"f&p_segment": "fp_segment"}   # must match jobs/extract/sources.yaml


def columns(view):
    with (DOC_DIR / f"{view}.csv").open(newline="") as f:
        rows = sorted(csv.DictReader(f), key=lambda r: int(r["ordinal"]))
    out = []
    for r in rows:
        name = RENAMES.get(r["column_name"], r["column_name"])
        assert name.replace("_", "").isalnum() and name == name.lower(), f"needs quoting: {name}"
        out.append((name, r["pg_type"], r["type_status"]))
    names = [c[0] for c in out]
    assert len(names) == len(set(names)), f"duplicate column in {view}"
    assert not {"load_id", "extracted_at"} & set(names), f"audit column clash in {view}"
    return out


def table_sql(view, cols):
    width = max(len(c[0]) for c in cols + [("extracted_at", "", "")])
    lines = []
    for name, typ, status in cols:
        flag = "" if status == "CONFIRMED" else "  -- type ASSUMED (as source)"
        lines.append(f"    {name.ljust(width)}  {typ},{flag}")
    lines.append(f"    {'load_id'.ljust(width)}  bigint      NOT NULL REFERENCES ctl.load_log (load_id),")
    lines.append(f"    {'extracted_at'.ljust(width)}  timestamptz NOT NULL")
    renamed = [f"{k} -> {v}" for k, v in RENAMES.items() if k in {c[0] for c in columns_raw(view)}]
    return (
        f"-- Raw landing table for source view FIN_REPORTING.{view.upper()}.\n"
        "-- Rows stored as received (same columns and types as the view), one set per extract load.\n"
        f"-- {len(cols)} source columns + load_id + extracted_at."
        + (f" Renamed: {', '.join(renamed)}." if renamed else "") + "\n"
        f"-- Generated by tools/gen_landing_ddl.py from docs/src_sf/{view}.csv\n\n"
        f"CREATE TABLE raw.{view} (\n" + "\n".join(lines) + "\n);\n\n"
        f"CREATE INDEX ix_{view}_load_id ON raw.{view} (load_id);\n\n"
        f"COMMENT ON TABLE raw.{view} IS 'Landing copy of FIN_REPORTING.{view.upper()}; one row set per ctl.load_log load_id';\n"
    )


def columns_raw(view):
    with (DOC_DIR / f"{view}.csv").open(newline="") as f:
        return [(r["column_name"],) for r in csv.DictReader(f)]


def main():
    for i, view in enumerate(VIEWS):
        cols = columns(view)
        path = SQL_DIR / f"V{FIRST_VERSION + i}__raw_{view}.sql"
        path.write_text(table_sql(view, cols))
        print(f"{path.name}: {len(cols)} + 2 audit columns")


if __name__ == "__main__":
    main()
